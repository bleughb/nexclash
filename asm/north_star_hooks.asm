; The game uses slot 3 for level data. Every gate gives it back before
; resuming the game. The interrupt copier itself uses slots 2, 4 and 7.
        ORG $386e
rom:
        MACRO GATE gate_label, dest_addr
gate_label: nextreg $53,26
        jp dest_addr
        ENDM
        GATE g_prepare,prepare
        GATE g_begin,begin
        GATE g_finish,finish
        GATE g_player,player
        GATE g_actor,actor
        GATE g_lance,lance
        GATE g_reset,reset
        GATE g_name,name_reset
        GATE g_caption,caption
        GATE g_wipe,wipe
        GATE g_final,finale
prepare_out:
        nextreg $53,11
        ld ($faed),a
        ret
; Return addresses for displaced instructions that use the game's stack.
copy_in: ld d,$40
        ld h,$80
        jp $fb2e
copy_out:
        nextreg $53,11
        pop hl
        pop de
        pop bc
        jp $fc50
player_out:
        nextreg $53,11
        jp $a679
actor_out:
        nextreg $53,11
        push hl
        push de
        ld hl,0
        jp $ae27
lance_out:
        nextreg $53,11
        push hl
        ld bc,$08ff
        jp $ab4d
reset_out:
        nextreg $53,11
        jp $bfa9
