; No game register or flag changes on these observation paths.
reset:  push af
        xor a
        ld (V_COUNT),a
        ld (V_CAPTION),a
        pop af
        jp reset_out
name_reset:
        push af
        push hl
        ld hl,5
        add hl,sp
        ld a,(hl)
        cp $ad
        jr z,.done
        xor a
        ld (V_COUNT),a
        ld (V_CAPTION),a
.done:  pop hl
        pop af
        jp name_out
caption:
        push af
        ld a,1
        ld (V_CAPTION),a
        pop af
        jp caption_out
player: ld hl,($a208)
        push bc
        ld bc,32
        call remember
        pop bc
        jp player_out
actor:  call remember
        jp actor_out
lance:  push bc
        ld bc,$0808                 ; B=8 identifies the one-byte art format
        call remember
        pop bc
        jp lance_out
remember:
        push af
        push hl
        ld a,(V_COUNT)
        cp 32
        jr nc,.done
        inc a
        ld (V_COUNT),a
        dec a
        add a,a
        ld l,a
        add a,a
        add a,l
        add a,low DESCRIPTORS
        ld l,a
        ld h,high DESCRIPTORS
        ld (hl),e
        inc l
        ld (hl),d
        inc l
        pop de
        ld (hl),e
        inc l
        ld (hl),d
        inc l
        ld (hl),c
        inc l
        ld (hl),b
        ex de,hl
        ; HL is the game's plot address. Restore the original art pointer.
        dec e
        dec e
        dec e
        dec e
        dec e
        push hl
        ex de,hl
        ld e,(hl)
        inc l
        ld d,(hl)
.done:  pop hl
        pop af
        ret
; Direct ULA transitions. The death wipe still needs progressive sprite clipping.
wipe:   nextreg $15,0
        jp wipe_out
finale: nextreg $15,0
        jp final_out

prepare:
        push af
        push bc
        push de
        push hl
        exx
        push bc
        push de
        push hl
        exx
        push ix
        HLIB_SPEED_IN V_SPEED
        call hlib_line
        ld (V_START),hl
        nextreg $55,84
        call masks
        nextreg $55,5
        ld a,1
        ld (V_PREPARED),a
        ; The previous ISR released the CPU just after DMA. Spend that
        ; advance here, where the next frame's descriptors are complete.
        call hlib_line
        ld de,(V_START)
        or a
        sbc hl,de
        jr nc,.elapsed
        ld de,312
        add hl,de
.elapsed:
        ex de,hl
        ; Charge the plot gates and the fixed prepare/return instructions
        ; against the same advance. A descriptor costs about two ULA lines.
        ld a,(V_COUNT)
        add a,a
        add a,2
        ld c,a
        ld b,0
        ld hl,(V_CREDIT)
        or a
        sbc hl,bc
        jr c,.ready
        ld (V_CREDIT),hl
        or a
        sbc hl,de
        jr c,.ready
        jr z,.ready
        ld hl,(V_START)
        ld de,(V_CREDIT)
        add hl,de
        ld de,312
        or a
        sbc hl,de
        jr nc,.wrapped
        add hl,de
.wrapped:
        ex de,hl
        call wait_line
.ready:
        xor a
        ld (V_CREDIT),a
        ld (V_CREDIT+1),a
        HLIB_SPEED_OUT_A V_SPEED
        pop ix
        exx
        pop hl
        pop de
        pop bc
        exx
        pop hl
        pop de
        pop bc
        pop af
        jp prepare_out

begin:  HLIB_SPEED_IN V_SPEED
        ld a,1
        ld (V_OPEN),a
        ; The stock copier lasts just under one field at 3.5 MHz. Capture
        ; its starting phase after the original, variable-length beeper.
        ld bc,$243b
        ld a,$1f
        out (c),a
        inc b
        in a,(c)
        sub 2
        ld (V_ENDLINE),a
        nextreg $55,86
        ld hl,stage_packet
        call run_dma
        nextreg $55,5
        nextreg $52,86
        jp copy_in
finish: ld a,(V_OPEN)
        or a
        jp z,copy_out               ; a diagnostic snapshot may start mid-copy
        ld (V_SP),sp
        ld sp,$8000
        nextreg $55,84              ; alpha, separate from both native images
        exx
        push bc
        push de
        push hl
        exx
        push ix
        push iy
        ld a,(V_PREPARED)
        or a
        call z,masks
        call patterns
        pop iy
        pop ix
        exx
        pop hl
        pop de
        pop bc
        exx
        nextreg $52,10
        nextreg $55,86
        ld de,$0101                ; present together at line 257
        call wait_line
        ld hl,show_packet
        call run_dma
        ld a,(V_TILES)
        ld hl,ATTRS
        call hlib_commit
        nextreg $15,1
        nextreg $55,5
        call hlib_line
        ex de,hl
        ld a,(V_ENDLINE)
        ld l,a
        ld h,0
        or a
        sbc hl,de
        jr nc,.credit
        ld de,312
        add hl,de
.credit:
        ld (V_CREDIT),hl
        xor a
        ld (V_OPEN),a
        ld sp,(V_SP)
        HLIB_SPEED_OUT_A V_SPEED
        jp copy_out
wait_line:
        ld bc,$243b
.poll:  ld a,$1e
        out (c),a
        inc b
        in a,(c)
        dec b
        and 1
        cp d
        jr nz,.poll
        ld a,$1f
        out (c),a
        inc b
        in a,(c)
        dec b
        cp e
        jr nz,.poll
        ret
run_dma:
        ld bc,(show_packet-stage_packet)*256+$6b
        otir
        ret
        MACRO PACKET src, length, mode, dst
        db $83,$c3,$7d
        dw src,length
        db mode,$10,$ad
        dw dst
        db $82,$cf,$87
        ENDM
stage_packet: PACKET $4000,8192,$14,$a000
show_packet:  PACKET $a000,6912,$14,$4000
clear_packet: PACKET zero,6912,$24,$a000
zero:   db 0
; Only the union of opaque bits is needed. The native finished bitmap
; supplies ink/paper after all overlaps. The original draw routines still
; do every save-under, collision check and pickup update themselves.
masks:  ld hl,clear_packet
        call run_dma
        ld ix,DESCRIPTORS
        ld a,(V_COUNT)
        or a
        ret z
.obj:   push af
        ld l,(ix+2)
        ld h,(ix+3)                 ; native destination; do not wrap an offscreen Y
        ld e,(ix+0)
        ld d,(ix+1)
        ld c,(ix+4)
        call mark_tile_row
.row:   push bc
        push hl
        ld a,h
        sub $80
        cp $18
        jr nc,.skip
        add a,$a0
        ld h,a
        ld a,(ix+5)
        cp 8
        jr nz,.wide
        ld a,(de)
        cpl
        inc de
        ex de,hl
        or (hl)
        inc hl
        ex de,hl
        or (hl)
        ld (hl),a
        jr .rowdone
.wide:  ld b,a                      ; native right shift
        push hl
        ex de,hl
        ld d,h
        ld e,l
        inc de
        inc de
        inc de                      ; DE=ink, HL=mask
        ld c,0                      ; previous unshifted byte
        exx
        pop hl                      ; HL'=alpha plane
        exx
        DUP 3
        ld a,(hl)
        cpl
        push hl
        ex de,hl
        or (hl)
        ex de,hl
        ld d,c                      ; high byte is the preceding unshifted opacity
        ; DE used as the shift register; restore pointers from HL afterwards.
        ld e,a
        ld c,a
        bsrl de,b
        ld a,e
        exx
        or (hl)
        ld (hl),a
        inc l
        exx
        pop hl
        inc hl
        ld d,h
        ld e,l
        inc de
        inc de
        inc de
        EDUP
        ld a,b
        or a
        jr z,.no_tail
        push de
        ld d,c
        ld e,0
        bsrl de,b
        ld a,e
        exx
        or (hl)
        ld (hl),a
        exx
        pop de
.no_tail:
        jr .rowdone
.skip:  ld a,(ix+5)
        cp 8
        jr z,.two
        inc de
        inc de
        inc de
        inc de
.two:   inc de
        inc de
.rowdone:
        pop hl
        inc h
        ld a,h
        and 7
        jr nz,.sametile
        call next_band
        call mark_tile_row
.sametile:
        pop bc
        dec c
        jp nz,.row
        ld bc,6
        add ix,bc
        pop af
        dec a
        jp nz,.obj
        ld a,(V_CAPTION)
        or a
        ret z
        ld hl,$a0cc                 ; native caption overwrites four + three bytes
        ld b,16
.clip:  push hl
        xor a
        DUP 4
        ld (hl),a
        inc l
        EDUP
        inc l
        ld (hl),a
        inc l
        ld (hl),a
        inc l
        ld (hl),a
        pop hl
        inc h
        ld a,h
        and 7
        call z,next_band
        djnz .clip
        ret

mark_tile_row:
        push hl
        ld a,h
        sub $80
        cp $18
        jr nc,.end
        and $18
        rrca
        rrca
        rrca
        add a,$b8
        ld h,a
        ld a,l
        and $de                     ; one flag for a 16x16 tile
        ld l,a
        ld a,1
        ld (hl),a
        inc l
        inc l
        ld (hl),a
        inc l
        inc l
        ld (hl),a
.end:   pop hl
        ret

next_band:
        ld a,h
        sub 8
        ld h,a
        ld a,l
        add a,32
        ld l,a
        and $e0
        ret nz
        ld a,h
        add a,8
        ld h,a
        ret

patterns:
        ; Store alternate registers used by the tile expansion.
        xor a
        ld (V_TILES),a
        ld a,(HLIB_V_DB)
        ld (V_SLOT),a
        srl a
        ld bc,$303b
        out (c),a                   ; first byte of inactive half
        ld ix,TILEPTR
        ld iy,ATTRS
        ld a,112
.loop:  ld (V_REMAIN),a
        ld l,(ix+0)
        ld h,(ix+1)
        ld (V_POS),hl
        ld a,h
        and $18
        rrca
        rrca
        rrca
        add a,$b8
        ld h,a
        ld a,(hl)
        or a
        jr z,.next
        ld hl,(V_POS)
        call nonempty
        jr z,.next
        ld hl,(V_POS)
        call emit_tile
        ld hl,(V_POS)
        ld a,l
        and 31
        add a,a
        add a,a
        add a,a
        add a,32
        ld (iy+0),a
        ld a,0
        adc a,0
        ld (iy+2),a
        ld a,h
        and $18
        rlca
        rlca
        rlca
        ld b,a
        ld a,l
        and $e0
        rrca
        rrca
        or b
        add a,32
        ld (iy+1),a
        ld a,(V_SLOT)
        inc a
        ld (V_SLOT),a
        dec a
        srl a
        or $c0
        ld (iy+3),a
        ld a,(V_SLOT)
        dec a
        and 1
        rrca
        rrca
        or $80
        ld (iy+4),a
        ld bc,5
        add iy,bc
        ld a,(V_TILES)
        inc a
        ld (V_TILES),a
        cp 64
        ret z
.next:  inc ix
        inc ix
        ld a,(V_REMAIN)
        dec a
        jp nz,.loop
        ret
nonempty:
        xor a
        DUP 2
        DUP 8
        or (hl)
        inc l
        or (hl)
        dec l
        inc h
        EDUP
        ld bc,$f820
        add hl,bc
        EDUP
        or a
        ret
; HL = alpha, DE = corresponding native mirror. Four packed pixel pairs per
; byte. Two 256-byte tables encode all alpha/ink combinations of four pixels.
        MACRO EMIT_BYTE
        ld a,(hl)
        or a
        jr z,1F
        ld b,a
        ld a,(de)
        ld c,a
        swapnib
        xor b
        and 15
        xor b
        exx
        ld l,a
        ld a,(hl)
        out ($5b),a
        inc h
        ld a,(hl)
        out ($5b),a
        dec h
        exx
        ld a,b
        swapnib
        xor c
        and $f0
        xor c
        exx
        ld l,a
        ld a,(hl)
        out ($5b),a
        inc h
        ld a,(hl)
        out ($5b),a
        dec h
        exx
        inc l
        inc e
        jr 2F
1 out ($5b),a
        out ($5b),a
        out ($5b),a
        out ($5b),a
        inc l
        inc e
2
        ENDM
emit_tile:
        ld a,h
        sub $60
        ld d,a
        ld e,l
        exx
        ld h,high LUT0
        exx
        ld a,2
.half:  push af
        ld a,8
.eight: push af
        EMIT_BYTE
        EMIT_BYTE
        dec l
        dec l
        dec e
        dec e
        inc d
        inc h
        pop af
        dec a
        jp nz,.eight
        ld bc,$f820
        add hl,bc
        ex de,hl
        add hl,bc
        ex de,hl
        pop af
        dec a
        jp nz,.half
        ret
