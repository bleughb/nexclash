        nextreg $53,11
        ld a,71
        call $c42f
        jp $c32f
rom_end:

        ORG $6000
work:
HLIB_V_DB EQU $7800
HLIB_DB_HALF EQU 64                 ; 64 four-bit patterns per half
HLIB_DB_SPR0 EQU 0
V_SPEED EQU $7802
V_OPEN EQU $7803
V_ENDLINE EQU $7804
V_COUNT EQU $7805
V_CAPTION EQU $7806
V_TILES EQU $7807
V_SLOT EQU $7808
V_REMAIN EQU $7809
V_POS EQU $780a
V_SP EQU $780c
V_CREDIT EQU $780e
V_START EQU $7810
V_PREPARED EQU $7812
DESCRIPTORS EQU $7820              ; 32 six-byte descriptors
ATTRS EQU $7900
TILEPTR EQU $7b00                  ; 112 screen addresses, generated by builder
LUT0 EQU $7c00                     ; two packed pixels per table
LUT1 EQU $7d00
HLIB_V_PACE EQU $7a90
HLIB_PACE_NL EQU 312
