"""Pssst (Ultimate Play The Game, 1983, 16K) engine 'pssst'. Additive module: reachable only through is_pssst().
Facts, design, results: games/pssst.md.

The game's plotter is Jetpac's (the same routine at other addresses), and this engine is jetpac_v11's shape with one
difference: the game goes on drawing every figure into the bitmap and nothing of the bitmap changes; the sprites
lie on the same pixels in the object's own colour, and only the colour the game paints over a figure's cells is not
painted for the objects that have sprites.

Game facts:
  0x75D0  move-and-redraw plotter: per object, erase the old frame (CPL/AND) and draw the new one (OR) line by
          line upwards (0x7585), wrapping within the 32-byte row. Graphic = [y offset, W, H, W*H bytes, rows
          BOTTOM line first].
  0x74C0  new-frame set-up (IX = object): DE -> graphic, 0x759A -> HL = screen address of the bottom line; 0x74D0
          is right after it (the draw hook).
  0x7521 / 0x7526  erase-only entries (object removed or changing graphic): hide.
  0x7450  paints (IX+3) over the figure's cells: its CALLs from the handlers of the main table's objects go to a
          copy that stores nothing.
  0x5F59  bitmap clear (every new screen): hide all.
  Graphics: 49, all fixed data (0x769A-0x7FD1); the tables 0x761A / 0x764A and pointers in the code name them.
  Objects: the main table 0x5E6C + 8i, i = 0-15 (+0 type/dir, +1 x, +2 y, +3 colour). The lives' icons (IX
  0x5E0F) and the leaves (IX 0x5E3C) are drawn once and left on the screen: no sprite, the game's own colour.
Hooks (asm/pssst_hooks.asm, alt ROM image 1, stateless; tables asm/pssst_tables.asm generated by
`python -m nexclash.pssst tables`): each object owns 6 sprites (2 rows x up to 3 placements: 2 columns + 1 copy
wrapped to the left edge, as the ULA row wrap); colour = the object's (IX+3) ink (palette offset ink + 8 * bright,
index 1).
"""
