w16 = lambda m, a: m[a] | m[a + 1] << 8


def image(m, a):
    """Graphic at a -> (W, H, {(x, r)}): x pixel from the byte column, r = 0 bottom line, or None."""
    W, H = m[a + 1], m[a + 2]
    if not (1 <= W <= 4 and 1 <= H <= 32):
        return None
    return W, H, {(8 * (k % W) + b, k // W) for k in range(W * H) for b in range(8)
                  if m[a + 3 + k] & (0x80 >> b)}


def graphics(m0):
    """{('s', addr): image} for every graphic. Each must end where the next starts or before it."""
    g = {}
    for i, a in enumerate(GRAPHICS):
        img = image(m0, a)
        end = a + 3 + m0[a + 1] * m0[a + 2]
        if img is None or end > (GRAPHICS[i + 1] if i + 1 < len(GRAPHICS) else GFX_HI):
            raise ValueError('no graphic at 0x%04X in this snapshot' % a)
        g[('s', a)] = img
    return g


def pointers(m0):
    """Words in the game's code and tables that point at a graphic's header, outside the known ones: none expected
    (a graphic the tables do not hold would be drawn with no sprite and no colour)."""
    out = []
    known = set(GRAPHICS)
    spans = [(a, a + 3 + m0[a + 1] * m0[a + 2]) for a in GRAPHICS]
    for a in range(0x5F00, GFX_LO):
        v = m0[a] | m0[a + 1] << 8
        if GFX_LO <= v < GFX_HI - 3 and v not in known and not any(lo < v < hi for lo, hi in spans):
            W, H = m0[v + 1], m0[v + 2]
            if 1 <= W <= 4 and 1 <= H <= 32 and v + 3 + W * H <= GFX_HI:
                out.append((a, v))
    return out


def layout(img):
    """image -> (key, xadj, cols, rows, trimmed pixels {(x, r)}) or None (empty)."""
    W, H, px = img
    if not px:
        return None
    x0 = min(x for x, r in px)
    x1 = max(x for x, r in px)
    cols = (x1 - x0) // 16 + 1
    rows = (H - 1) // 16 + 1
    t = frozenset((x - x0, r) for x, r in px)
    return t, x0, cols, rows


def build(m0):
    """-> (patterns bytes, entries {gkey: (pat, cols, rows, xadj, 0)})."""
    pats = bytearray()
    first = {}
    ent = {}
    for k, img in graphics(m0).items():
        lo = layout(img)
        if lo is None:
            continue
        t, x0, cols, rows = lo
        if cols > 2 or rows > 2:
            raise ValueError('graphic %s too big for 2x2 sprites' % (k,))
        if (t, rows) not in first:
            first[(t, rows)] = len(pats) // 128
            for rr in range(rows):
                for cc in range(cols):
                    for j in range(16):             # pattern line j (top down) of row rr
                        r = 16 * rows - 1 - (16 * rr + j)      # data row (0 = bottom)
                        for x in range(16 * cc, 16 * cc + 16, 2):
                            pats.append((1 if (x, r) in t else 0) << 4 | (1 if (x + 1, r) in t else 0))
        ent[k] = (first[(t, rows)], cols, rows, x0, 0)
    if len(pats) > 128 * 128:
        raise ValueError('%d patterns > 128' % (len(pats) // 128))
    return bytes(pats), ent


def tables_asm(ent):
    """The hooks' lookup table (asm/pssst_tables.asm)."""
    out = ['; GENERATED by `python -m nexclash.pssst tables` from the Pssst snapshot - do not edit.',
           '; gtab: dw graphic address; db pattern, layout (cols-1 | (rows-1)<<1), x adjust',
           'gtab:']
    for a in sorted(k[1] for k in ent):
        e = ent[('s', a)]
        out.append('        dw %d : db %d,%d,%d' % (a, e[0], (e[1] - 1) | (e[2] - 1) << 1, e[3]))
    out.append('        dw 0')
    return '\n'.join(out) + '\n'


def tables_text(pats, ent):
    return tables_asm(ent) + 'NPAT256 EQU %d\n' % ((len(pats) + 255) // 256)


def sprite_pixels(attr, pat):
    """Visible 4-bit sprite -> {(x, y)} ink pixels in ULA coordinates."""
    a0, a1, a2, a3, a4 = attr
    if not a3 & 0x80:
        return set()
    x = a0 + (a2 & 1) * 256 - 32
    y = a1 + (a4 & 1) * 256 - 32
    n = (a3 & 0x3F) * 2 + (1 if a4 & 0x40 else 0)
    out = set()
    for j in range(16):
        for k in range(16):
            b = pat[n * 128 + j * 8 + k // 2] if n * 128 + j * 8 + k // 2 < len(pat) else 0
            if (b >> 4) if k % 2 == 0 else (b & 15):
                out.add((x + k, y + j))
    return out


def palette_colour(offset, nibble):
    """The default build's palette: offset n, nibbles 1 and 15 = Spectrum colour n."""
    return offset


def sprite_colours(attr, pat):
    """Visible 4-bit sprite -> {(x, y): Spectrum colour} in ULA coordinates."""
    a0, a1, a2, a3, a4 = attr
    if not a3 & 0x80:
        return {}
    x = a0 + (a2 & 1) * 256 - 32
    y = a1 + (a4 & 1) * 256 - 32
    n = (a3 & 0x3F) * 2 + (1 if a4 & 0x40 else 0)
    out = {}
    for j in range(16):
        for k in range(16):
            at = n * 128 + j * 8 + k // 2
            b = pat[at] if at < len(pat) else 0
            v = (b >> 4) if k % 2 == 0 else (b & 15)
            if v:
                out[(x + k, y + j)] = palette_colour(a2 >> 4, v)
    return out


def main(argv=None):
    import argparse
    from skoolkit.snapshot import get_snapshot
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['tables'])
    ap.add_argument('z80')
    a = ap.parse_args(argv)
    m0 = list(get_snapshot(a.z80))
    pats, ent = build(m0)
    open(os.path.join(_ROOT, 'asm', 'pssst_tables.asm'), 'w').write(tables_text(pats, ent))
    print('%d graphics, %d patterns -> asm/pssst_tables.asm; other pointers at graphics: %s' % (len(ent), len(pats) // 128, pointers(m0)))


if __name__ == '__main__':
    main()


