def load_profile():
    return json.load(open(_profile_path()))


def is_pssst(snap):
    if getattr(snap, 'machine', '48K') != '48K':
        return False
    sig = bytes.fromhex(SIGNATURE[1])
    try:
        return bytes(snap.memory[SIGNATURE[0]:SIGNATURE[0] + len(sig)]) == sig
    except Exception:
        return False


