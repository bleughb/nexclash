"""Cookie (Ultimate Play The Game, 1983, 16K) engine 'cookie'. Additive module: reachable only through is_cookie().
Facts, design, results: games/cookie.md.

The game's plotter has Jetpac's and Pssst's control flow with another row routine, and this engine is pssst's shape
at this game's addresses: the game goes on drawing every figure into the bitmap and nothing of the bitmap changes;
the sprites lie on the same pixels in the object's own colour, and the colour the game paints over a figure's cells
is not painted.

Game facts:
  0x763A  move-and-redraw plotter: per object, the old frame XORed out and the new one XORed in, line by line
          upwards. Graphic = [H, H rows of 2 bytes, BOTTOM line first]: 16 pixels wide, shifted at run time to the
          pixel x; nothing is drawn below line 159 (the set-up cuts the rows under it).
  0x7587  new-frame set-up (IX = object, DE = graphic); its CALL of the screen address at 0x75A9 is the draw hook.
  0x7602 / 0x7607  erase-only entries: hide.
  0x74EE  paints (IX+3) over the figure's cells (the game rewrites its column limit, 0x7516, as it runs): its
          store at 0x7519 becomes a read.
  0x74D4  bitmap clear (every new screen): hide all.
  Graphics: the table 0x7702 (a word a type, types 1-48).
  Objects: 0x5F35 + 8i, i = 0-9 (+0 type, +1 x, +2 y, +3 colour).
Hooks (asm/cookie_hooks.asm, alt ROM image 1, stateless; tables asm/cookie_tables.asm generated by
`python -m nexclash.cookie tables`): each object owns 2 sprites (16 pixels wide, up to 32 lines); colour = the
object's (IX+3) ink (palette offset ink + 8 * bright, index 1).
"""
