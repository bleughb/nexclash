def _profile_path():
    for p in (os.path.join(_ROOT, 'docs', 'profiles', 'cookie.json'), os.path.join(_HERE, 'cookie.json')):
        if os.path.exists(p):
            return p
    raise FileNotFoundError('cookie.json profile not found')


def load_profile():
    return json.load(open(_profile_path()))


def is_cookie(snap):
    if getattr(snap, 'machine', '48K') != '48K':
        return False
    sig = bytes.fromhex(SIGNATURE[1])
    try:
        return bytes(snap.memory[SIGNATURE[0]:SIGNATURE[0] + len(sig)]) == sig
    except Exception:
        return False


