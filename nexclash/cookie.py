def verify(patch, z80, rzx=None, frames=6000, keys=None, stop=None, collect=0, progress=None):
    """Run the original game (a recording, or a free run with a key schedule); at every hook site, at the colour
    paint's CALLs and at every interrupt run original and patched code from the same state and compare.
    -> (Counter, examples, states)."""
    from . import simrun
    c = collections.Counter()
    ex = collections.defaultdict(list)
    alt = _alt(patch)
    off = alt_outside_hooks(patch, alt)
    if off:
        c['alt ROM image bytes outside the hooks not Sinclair\'s!'] = len(off)
        ex['alt ROM image bytes outside the hooks not Sinclair\'s'].append((0, len(off), [hex(a) for a in off[:6]]))
    site_bytes = {a + k for a, old, new in patch.sites for k in range(len(new))}
    ns = NextState(patch.pats)
    st = {'frame': 0}
    states = []
    cnt = collections.Counter()
    WATCH = set(SITE_KIND) | set(INTERIORS) | {0x0038} | set(PACE_SITES)

    def fail(k, info=()):
        c[k + '!'] += 1
        if len(ex[k]) < 5:
            ex[k].append((st['frame'],) + tuple(info))

    class H:
        def on_sim(self, sim):
            st['sim'] = sim

        def on_write(self, addr, value, pc, mem):
            if addr in site_bytes or addr >= 0x8000:
                fail('game wrote a patch site or above 0x7FFF', (addr, pc))

        def on_read(self, addr, pc, mem):
            if addr >= 0x8000 and not st.get('busy'):     # the game's own reads, not this verifier's
                fail('game read above 0x7FFF (the hook RAM is there)', (addr, pc))

        def before(self, pc):
            if pc not in WATCH:
                return
            st['busy'] = True
            try:
                self.check(pc)
            finally:
                st['busy'] = False

        def check(self, pc):
            cnt[pc] += 1
            if pc in PACE_SITES:
                sim = st['sim']
                R, get = sim.registers, sim.memory.__getitem__
                if collect and pc in PLOT_STACK and c['collected %d' % pc] < collect:
                    c['collected %d' % pc] += 1
                    states.append((pc, list(R), bytes(get(a) for a in range(65536)), None))
                c['pace sites'] += 1
                ns_s = NextState(patch.pats)
                ns_s.nr[0x07] = 3 if PACE_SITES[pc][2] == 'end' else 0
                for k in pace_event(patch, pc, get, R, ns_s, alt, _rw()):
                    fail('pace site %04X: %s' % (pc, k[0] if isinstance(k, tuple) else k), k[1:] if isinstance(k, tuple) else ())
                if pc in PLOT_STACK:
                    c['draws from their entry'] += 1
                    for k in plot_event(patch, pc, get, R, alt, _rw()):
                        fail('draw from its entry %04X: %s' % (pc, k[0] if isinstance(k, tuple) else k), k[1:] if isinstance(k, tuple) else ())
                return
            if pc == 0x0038:
                sim = st['sim']
                c['IM 1 interrupts (ROM 0x0038)'] += 1
                for k in isr_event(sim.memory.__getitem__, sim.registers, alt, _rw(), getattr(patch, 'hook_range', patch.altrom)):
                    fail('IM 1 handler: %s' % (k[0] if isinstance(k, tuple) else k), k[1:] if isinstance(k, tuple) else ())
                return
            if pc not in SITE_KIND:
                return
            sim = st['sim']
            R, mem = sim.registers, sim.memory
            get = mem.__getitem__
            kind = SITE_KIND[pc]
            sp_ = R[12]
            if kind == 'nw' and get(sp_) | get(sp_ + 1) << 8 not in DRAW_ONLY:
                pass                            # (the unit cases start from a draw that erases nothing)
            elif collect and c['collected ' + kind] < collect and (kind != 'at' or pc in AT_SITES):
                c['collected ' + kind] += 1
                states.append((kind, list(R), bytes(get(a) for a in range(65536)),
                               [list(x) for x in ns.attr]))
            fl, npx, note = event(patch, kind, get, R, ns, alt, _rw())
            c[kind] += 1
            c['sprite pixels compared'] += npx
            if kind == 'nw' and note == 'left':
                c['figures left to the game (no object slot)'] += 1
            elif kind == 'nw':
                c['figures as sprites'] += 1
                c['figures across the right edge'] += note == 'edge'
            if kind == 'at':
                c['paints not painted' if pc in AT_SITES else 'paints left to the game'] += 1
                if note == 'late':
                    c['paints of another colour than the sprites took at the plot'] += 1
            for k in fl:
                fail('%s: %s' % (kind, k[0] if isinstance(k, tuple) else k),
                     k[1:] if isinstance(k, tuple) else ())

        def on_frame(self, n):
            st['frame'] = n
            if progress and n % 1000 == 0:
                progress(n, c)

    c['frames'] = simrun.run(z80, [rzx] if rzx else None, H(), frames=frames, keys=keys, stop=stop)
    # an instruction a hook replays is reached only straight after its site; the other bytes of a patched site never
    by_site = collections.defaultdict(set)
    for a, site in REPLAYED.items():
        by_site[site].add(a)
    for site, inner in by_site.items():
        if any(cnt[a] != cnt[site] for a in inner):
            c['a replayed instruction (0x%04X) reached other than from its site!' % site] += 1
    for a in INTERIORS:
        if a not in REPLAYED and cnt[a]:
            c['jump into a patched instruction (0x%04X)!' % a] += 1
    return c, dict(ex), states


