w16 = lambda m, a: m[a] | m[a + 1] << 8


def image(m, a):
    """Graphic at a -> (W, H, {(x, r)}): x pixel from its left, r = 0 bottom line, or None."""
    H = m[a]
    if not 1 <= H <= 32:
        return None
    return 2, H, {(8 * (k % 2) + b, k // 2) for k in range(2 * H) for b in range(8)
                  if m[a + 1 + k] & (0x80 >> b)}


def graphic_addresses(m0):
    return sorted({w16(m0, GFX_TAB + 2 * i) for i in range(GFX_TYPES)})


def graphics(m0):
    """{('s', addr): image} for every graphic the type table names."""
    g = {}
    for a in graphic_addresses(m0):
        img = image(m0, a)
        if img is None:
            raise ValueError('no graphic at 0x%04X in this snapshot' % a)
        g[('s', a)] = img
    return g


def pointers(m0):
    """(Nothing but the type table names a graphic: the handlers give types.)"""
    return []


def layout(img):
    """image -> (pixels {(x, r)}, 0, 1 column, rows): the 16 pixels as they are, no trim (the hooks place by x)."""
    W, H, px = img
    return frozenset(px), 0, 1, (H - 1) // 16 + 1


def shape_key(t, rows):
    """A shape's name in a painted map (the painting sheet has one picture a shape)."""
    import hashlib
    return hashlib.md5(repr((sorted(t), rows)).encode()).hexdigest()[:16]


def shape_nibbles(t, rows, cmap):
    """{(x, r): nibble} of a shape: 1 = the game's own colour, 2-14 = a fixed colour of the painted map."""
    f = cmap['figures'].get(shape_key(t, rows)) if cmap else None
    if not f:
        return {q: 1 for q in t}
    H = max(r for _, r in t) + 1
    return {(x, r): int(f[H - 1 - r][x], 16) or 1 for x, r in t}


def build(m0, cmap=None):
    """-> (patterns bytes, entries {gkey: (pat, cols, rows, xadj, 0)}). cmap: a painted map (COLOURS_NAME)."""
    cache = {}

    def nib(t, rows, x, r):
        if (x, r) not in t:
            return 0
        if (t, rows) not in cache:
            cache[(t, rows)] = shape_nibbles(t, rows, cmap)
        return cache[(t, rows)][(x, r)]
    pats = bytearray()
    first = {}
    ent = {}
    for k, img in graphics(m0).items():
        t, x0, cols, rows = layout(img)
        if cols > 2 or rows > 2:
            raise ValueError('graphic %s too big for 2x2 sprites' % (k,))
        if (t, rows) not in first:
            first[(t, rows)] = len(pats) // 128
            for rr in range(rows):
                for cc in range(cols):
                    for j in range(16):             # pattern line j (top down) of row rr
                        r = 16 * rows - 1 - (16 * rr + j)      # data row (0 = bottom)
                        for x in range(16 * cc, 16 * cc + 16, 2):
                            pats.append(nib(t, rows, x, r) << 4 | nib(t, rows, x + 1, r))
        ent[k] = (first[(t, rows)], cols, rows, x0, 0)
    if len(pats) > 128 * 128:
        raise ValueError('%d patterns > 128' % (len(pats) // 128))
    return bytes(pats), ent


def tables_asm(ent):
    """The hooks' lookup table (asm/cookie_tables.asm)."""
    out = ['; GENERATED by `python -m nexclash.cookie tables` from the Cookie snapshot - do not edit.',
           '; gtab: dw graphic address; db pattern, rows - 1',
           'gtab:']
    for a in sorted(k[1] for k in ent):
        e = ent[('s', a)]
        out.append('        dw %d : db %d,%d' % (a, e[0], e[2] - 1))
    out.append('        dw 0')
    return '\n'.join(out) + '\n'


def tables_text(pats, ent):
    return tables_asm(ent) + 'NPAT256 EQU %d\n' % ((len(pats) + 255) // 256)


def sprite_pixels(attr, pat):
    """Visible 4-bit sprite -> {(x, y)} ink pixels in ULA coordinates."""
    a0, a1, a2, a3, a4 = attr
    if not a3 & 0x80:
        return set()
    x = a0 + (a2 & 1) * 256 - 32
    y = a1 + (a4 & 1) * 256 - 32
    n = (a3 & 0x3F) * 2 + (1 if a4 & 0x40 else 0)
    out = set()
    for j in range(16):
        for k in range(16):
            b = pat[n * 128 + j * 8 + k // 2] if n * 128 + j * 8 + k // 2 < len(pat) else 0
            if (b >> 4) if k % 2 == 0 else (b & 15):
                out.add((x + k, y + j))
    return out


def palette_colour(offset, nibble):
    """Offset n, nibbles 1 and 15 = Spectrum colour n (the game's own); nibbles 2-14 = a fixed colour: 0x100 + nibble."""
    return offset if nibble in (1, 15) else 0x100 + nibble


def load_colours(z80=None, path=None):
    """The painted map beside the snapshot (it holds the figures: not in the repository), or None."""
    p = path or (os.path.join(os.path.dirname(os.path.abspath(str(z80))), COLOURS_NAME) if z80 else None)
    return json.load(open(p)) if p and os.path.exists(p) else None


def sprite_colours(attr, pat):
    """Visible 4-bit sprite -> {(x, y): Spectrum colour} in ULA coordinates."""
    a0, a1, a2, a3, a4 = attr
    if not a3 & 0x80:
        return {}
    x = a0 + (a2 & 1) * 256 - 32
    y = a1 + (a4 & 1) * 256 - 32
    n = (a3 & 0x3F) * 2 + (1 if a4 & 0x40 else 0)
    out = {}
    for j in range(16):
        for k in range(16):
            at = n * 128 + j * 8 + k // 2
            b = pat[at] if at < len(pat) else 0
            v = (b >> 4) if k % 2 == 0 else (b & 15)
            if v:
                out[(x + k, y + j)] = palette_colour(a2 >> 4, v)
    return out


def main(argv=None):
    import argparse
    from skoolkit.snapshot import get_snapshot
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['tables'])
    ap.add_argument('z80')
    a = ap.parse_args(argv)
    m0 = list(get_snapshot(a.z80))
    pats, ent = build(m0)
    open(os.path.join(_ROOT, 'asm', 'cookie_tables.asm'), 'w').write(tables_text(pats, ent))
    print('%d graphics, %d patterns -> asm/cookie_tables.asm; other pointers at graphics: %s' % (len(ent), len(pats) // 128, pointers(m0)))


if __name__ == '__main__':
    main()


