def _overlays(get, alt, psite, canvas=None):
    class O:
        def __init__(s):
            s.ov = {}

        def __getitem__(s, a):
            v = s.ov.get(a)
            if v is not None:
                return v
            if canvas is not None and canvas[0] <= a < canvas[1]:
                return 0
            return get(a)

        def __setitem__(s, a, v):
            if a >= 0x4000:
                s.ov[a] = v
            else:
                s.romw = getattr(s, 'romw', 0) + 1  # (the game's plotter stores into the ROM above the top of the screen)

        def __len__(s):
            return 65536

    class P(O):
        def __getitem__(s, a):
            if a < 0x4000:
                return alt[a]
            v = psite.get(a)
            if v is not None:
                return v
            return O.__getitem__(s, a)

        def __setitem__(s, a, v):
            if a < 0x4000:
                s.romw = getattr(s, 'romw', 0) + 1
            else:
                s.ov[a] = v
    return O, P


def _screen_set(ov):
    out = set()
    for a, v in ov.items():
        if 0x4000 <= a < 0x5800:
            y = ((a >> 5) & 0xC0) | ((a >> 8) & 7) | ((a >> 2) & 0x38)
            for k in range(8):
                if (v >> (7 - k)) & 1:
                    out.add(((a & 31) * 8 + k, y))
    return out


def obj_index(ix):
    d = ix - OBJ0
    return d >> 3 if 0 <= d < 8 * NOBJ and not d & 7 else None


def pace_event(patch, pc, get, R, ns, alt, Sim):
    """A pace window site, original and patched from the same state to the original's next instruction: every register
    with R, memory, the speed: an entry latches the speed and goes to 28 MHz, an end gives the latch back."""
    psite = {a + k: v for a, old, new in patch.sites for k, v in enumerate(new)}
    ret, dsp, role = PACE_SITES[pc]
    sp0 = R[12]

    def stop(r):
        return r[24] == ret and r[12] == (sp0 + dsp) & 0xFFFF
    O, P = _overlays(get, alt, psite)
    o, p = O(), P()
    so = _machine(Sim, o, list(R), NextState(b''))
    before = ns.nr.get(0x07, 0) & 3
    ns.events = []
    sp_ = _machine(Sim, p, list(R), ns, 'p')
    if not (_run(so, stop) and _run(sp_, stop)):
        return ['did not return']
    ro, rp = so.registers, sp_.registers
    f = []
    diff = [i for i in CMP if ro[i] != rp[i]]
    if diff:
        f.append(('registers differ', diff, [ro[i] for i in diff], [rp[i] for i in diff]))
    if getattr(p, 'romw', 0) != getattr(o, 'romw', 0):
        f.append(('patched code wrote ROM',))
    if any(e[0] in ('in', 'out') for e in ns.events) or any(e[1] != 0x07 for e in ns.events if e[0] == 'nr'):
        f.append(('hook touched more than the CPU speed',))
    dead = range(ro[12] - 64, ro[12])
    md = [a for a in set(o.ov) | set(p.ov) if a not in dead and a not in patch.ram_vars and o[a] != p[a]]
    if md:
        f.append(('memory differs', len(md), sorted(md)[:4]))
    if role == 'pre':
        if ns.nr.get(0x07, 0) & 3 != 3:
            f.append(('window not at 28 MHz',))
        if p[patch.syms['V_SPD']] != before:
            f.append(("the caller's speed not latched",))
    elif ns.nr.get(0x07, 0) & 3 != get(patch.syms['V_SPD']):
        f.append(("the caller's speed not given back",))
    return f


def plot_event(patch, pc, get, R, alt, Sim, speed=0):
    """A draw from its entry to the plot's return, original and patched: registers with R, memory, the caller's speed back."""
    psite = {a + k: v for a, old, new in patch.sites for k, v in enumerate(new)}
    sp0 = R[12]
    k = PLOT_STACK[pc]
    ret, end = get(sp0 + k) | get(sp0 + k + 1) << 8, sp0 + k + 2

    def stop(r):
        return r[24] == ret and r[12] == end
    O, P = _overlays(get, alt, psite)
    o, p = O(), P()
    so = _machine(Sim, o, list(R), NextState(b''))
    ns = NextState(patch.pats)
    ns.nr[0x07] = speed
    sp_ = _machine(Sim, p, list(R), ns, 'p')
    if not (_run(so, stop) and _run(sp_, stop)):
        return ['did not return']
    ro, rp = so.registers, sp_.registers
    f = []
    diff = [i for i in CMP if ro[i] != rp[i]]
    if diff:
        f.append(('registers differ', diff, [ro[i] for i in diff], [rp[i] for i in diff]))
    if ns.nr.get(0x07, 0) & 3 != speed:
        f.append(("the caller's speed not back at the plot's end",))
    dead = range(ro[12] - 64, ro[12])
    md = [a for a in set(o.ov) | set(p.ov) if a not in dead and a not in patch.ram_vars and o[a] != p[a]]
    if md:
        f.append(('memory differs', len(md), sorted(md)[:4]))
    return f


def event(patch, kind, get, R, ns, alt, Sim, speed=0):
    """One hook event, original and patched from the same state. -> (failures, pixels compared, note)."""
    psite = {a + k: v for a, old, new in patch.sites for k, v in enumerate(new)}
    sp0 = R[12]
    pc = R[24]
    w = lambda a: get(a) | get(a + 1) << 8
    f = []
    if kind == 'nw' and w(sp0) in NW_DIRECT:
        ret, end = NW_DIRECT[w(sp0)], sp0 + 2
    elif kind == 'nw':
        ret, end = w(sp0 + 2), sp0 + 4
    elif kind == 'cls':
        ret, end = pc + 3, sp0
    elif kind == 'at':                      # the paint's CALL (back after it) or JP (back at the handler's caller)
        op = AT_SITES.get(pc, AT_LEFT.get(pc))
        ret, end = (pc + 3, sp0) if op == 0xCD else (w(sp0), sp0 + 2)
    else:                                   # er: the routine's own caller
        ret, end = w(sp0), sp0 + 2

    def stop(r):
        return r[24] == ret and r[12] == end
    ix = R[8] << 8 | R[9]
    obj = obj_index(ix)
    O, P = _overlays(get, alt, psite)
    o, p = O(), P()
    so = _machine(Sim, o, list(R), NextState(b''))
    before = [list(a) for a in ns.attr]
    ns.events = []
    sp_ = _machine(Sim, p, list(R), ns, 'p')
    if not (_run(so, stop) and _run(sp_, stop)):
        return ['did not return'], 0, None
    ro, rp = so.registers, sp_.registers
    diff = [i for i in CMP if ro[i] != rp[i]]
    if diff:
        f.append(('registers differ', diff, [ro[i] for i in diff], [rp[i] for i in diff]))
    if getattr(p, 'romw', 0) != getattr(o, 'romw', 0):
        f.append(('patched code wrote ROM',))
    if any(e[0] in ('in', 'out') for e in ns.events):
        f.append(('port access in hook',))
    if any(e[1] not in (0x07, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39) for e in ns.events if e[0] == 'nr'):
        f.append(('NEXTREG other than sprite attributes / CPU speed',))
    if ns.nr.get(0x07, 0) & 3 != speed:
        f.append(('hook left the CPU at the wrong speed',))
    dead = range(ro[12] - 64, ro[12])
    keys = set(o.ov) | set(p.ov)
    cells = (0x5800, 0x5B00) if kind == 'at' and pc in AT_SITES else (0, 0)    # only the colour may differ, and only there
    md = [a for a in keys if not cells[0] <= a < cells[1] and a not in dead and a not in patch.ram_vars and o[a] != p[a]]
    if md:
        f.append(('memory differs', len(md), sorted(md)[:4]))
    changed = [i for i in range(128) if ns.attr[i] != before[i]]
    base = SPO * obj if obj is not None else None
    mine = set(range(base, base + SPO)) if base is not None else set()
    if kind == 'cls':
        if any(ns.attr[i][3] & 0x80 for i in range(128)):
            f.append(('sprite visible after screen clear',))
        return f, 0, None
    if kind == 'at':
        if changed:
            f.append(('sprites changed by the colour paint',))
        painted = {a: v for a, v in o.ov.items() if 0x5800 <= a < 0x5B00}
        if pc in AT_SITES:
            if obj is None:
                f.append(('the paint of an object with no sprites is not painted', hex(ix)))
            if any(0x5800 <= a < 0x5B00 for a in p.ov):
                f.append(('the patched paint wrote a colour',))
            # the colour the game paints now against the colour its sprites took at the plot
            a3 = get(ix + 3)
            shown = {ns.attr[i][2] >> 4 for i in mine if ns.attr[i][3] & 0x80}
            note = 'late' if painted and shown and shown != {(a3 & 7) | ((a3 >> 3) & 8)} else None
            return f, 0, note
        if obj is not None:
            f.append(('an object with sprites is still painted', hex(ix)))
        return f, 0, None
    if set(changed) - mine:
        f.append(('other sprites changed', sorted(set(changed) - mine)[:4]))
    if kind == 'er':
        if obj is not None and any(ns.attr[i][3] & 0x80 for i in mine):
            f.append(('sprite still visible after erase', obj))
        return f, 0, None
    # nw: the object's sprites against the figure (the graphic's 16 pixels at x, its bottom line at y, nothing under
    # line BOTTOM). The plotter XORs: on an empty screen the old frame would show too, so the original's own plot is
    # the reference only where the entry draws without erasing (DRAW_ONLY); there the figure must also be the model.
    gaddr = R[4] << 8 | R[5]
    x, y = get(ix + 1), get(ix + 2)
    model = figure_pixels(get, gaddr, x, y)
    edge = x > 240
    if w(sp0) in DRAW_ONLY:
        Oc, _ = _overlays(get, alt, psite, (0x4000, 0x5800))
        oc = Oc()
        sc = _machine(Sim, oc, list(R), NextState(b''), 'c')
        if not _run(sc, stop):
            return f + ['canvas run did not return'], 0, None
        drawn = _screen_set(oc.ov)
        if drawn != model and not edge:
            f.append(('the original plot is not the model of the figure', len(drawn ^ model)))
    if obj is None:
        if changed:
            f.append(('a figure of no object slot changed sprites', hex(ix)))
        return f, 0, 'left'
    got = ns.group_pixels(base)
    npx = len(model)
    if set(got) != model:
        f.append(('sprite pixels differ from the figure', len(set(got) ^ model)))
    if colours_wrong(patch, get, gaddr, x, y, get(ix + 3), got):
        f.append(('sprite colour is not the game\'s or the painted map\'s',))
    return f, npx, 'edge' if edge else None


def palette_wrong(nex, z80, fixed):
    """(offset, nibble) of every sprite palette entry 2..1+len(fixed) the build's set-up leaves different from the
    painted map's fixed colours (9 bits): its NEXTREG writes in the simulated boot replayed (0x43 select, 0x40 index,
    0x41 8-bit and 0x44 9-bit values; first sprite palette). The default build, whose set-up writes zeros there, is
    the negative."""
    from . import nextboot, z80tonex as zt
    st = nextboot.boot(nex, zt.Z80Snapshot(z80).pc)
    pal = [[None] * 256 for _ in range(8)]
    sel = idx = 0
    first, auto = None, True
    for r, v in st['nrlog']:
        if r == 0x43:
            sel, auto, first = (v >> 4) & 7, not v & 0x80, None
        elif r == 0x40:
            idx, first = v, None
        elif r == 0x41:                     # an 8-bit write also ends a 0x44 pair, as on the Next
            pal[sel][idx], first = v << 1 | (1 if v & 3 else 0), None
            idx = (idx + 1) & 255 if auto else idx
        elif r == 0x44:
            if first is None:
                first = v
            else:
                pal[sel][idx], first = first << 1 | (v & 1), None
                idx = (idx + 1) & 255 if auto else idx
    return [(o, n) for o in range(16) for n in range(2, 2 + len(fixed)) if pal[2][o * 16 + n] != fixed[n - 2]]


def colours_wrong(patch, get, g, x, y, a3, got):
    """Sprite pixels {(px, py): colour} of graphic g at (x, y) against this build: the game's ink (attribute a3) where
    the pixel is nibble 1, the painted map's fixed colour elsewhere. -> the pixels that differ."""
    ink = (a3 & 7) | ((a3 >> 3) & 8)
    nibs = figure_nibbles(patch, get, g)
    out = []
    for (px, py), v in got.items():
        n = nibs.get((px - x, y - py), 1)
        if v != (ink if n == 1 else 0x100 + n):
            out.append((px, py))
    return out


def figure_nibbles(patch, get, g):
    """{(x from the graphic's left, r from its bottom line): nibble} of graphic g as this build paints it."""
    if g not in patch._nibs:
        class M:
            def __getitem__(s, a):
                return get(a)
        img = image(M(), g)
        if img is None:                     # (not a graphic: nothing of it is painted)
            patch._nibs[g] = ({}, 0)
            return patch._nibs[g][0]
        t, x0, cols, rows = layout(img)
        patch._nibs[g] = ({(x + x0, r): n for (x, r), n in shape_nibbles(t, rows, patch.colours).items()}, x0)
    return patch._nibs[g][0]


def figure_pixels(get, g, x, y):
    """The figure the plotter draws for graphic g with its left at pixel x and its bottom line at y: lines 0 to BOTTOM,
    left of x = 256; nothing when y is above line TOP."""
    out = set()
    H = get(g)
    cut = (y - BOTTOM) & 0xFF           # the set-up's cut: rows under line BOTTOM, by a signed compare, so a bottom
    cut = cut if cut < 0x80 else 0      # line above TOP counts as far under the bottom and nothing is drawn
    for r in range(cut, H):
        line = y - r
        if not 0 <= line <= BOTTOM:
            continue
        v = get(g + 1 + 2 * r) << 8 | get(g + 2 + 2 * r)
        for b in range(16):
            if v & (0x8000 >> b) and x + b < 256:
                out.add((x + b, line))
    return out


def _rom3_path():
    from . import nextboot
    return nextboot.NEXT_ROM or os.environ.get('NEXCLASH_NEXT_ROM') or os.environ.get('NEXCLASH_ROM3')


def rom3():
    """NextZXOS's ROM3 (48K BASIC: the last 16K of enNextZX.rom, MD5 8c34d957, from the card's /machines/next):
    `--next-rom` / $NEXCLASH_NEXT_ROM as the shared ROM model (nextboot.system_rom3), never in the repo."""
    p = _rom3_path()
    if not p:
        raise ValueError("cookie verifies against NextZXOS's ROM3: give --next-rom or $NEXCLASH_NEXT_ROM (enNextZX.rom)")
    d = open(p, 'rb').read()
    if len(d) != 0x10000:
        raise ValueError('%s is not a 64K enNextZX.rom' % p)
    return d[-0x4000:]


def _alt(patch):
    """The alt ROM image as the Next's stub fills it (z80tonex.altrom_fill): the SYSTEM ROM3 copied first (NextZXOS's,
    with code at 0x386E-0x3CFE that its IM 1 handler and UDG print call), then bytes lo..hi of the patch page, then
    altrom_low over 0x0000-0x1FFF."""
    alt = bytearray(rom3())
    lo, hi = patch.altrom
    alt[lo:hi] = patch.page[lo - 0x2000:hi - 0x2000]
    low = getattr(patch, 'altrom_low', None)
    if low:
        alt[0:0x2000] = low[1]
    return alt


def alt_outside_hooks(patch, alt=None):
    """Addresses of the alt ROM image, outside the hook bytes, that are not Sinclair's 48K ROM (empty = whole image)"""
    from .build import rom48
    alt = alt if alt is not None else _alt(patch)
    rom = rom48()
    h0, h1 = getattr(patch, 'hook_range', patch.altrom)
    return [a for a in range(0x4000) if not h0 <= a < h1 and alt[a] != rom[a]]


def isr_event(get, R, alt, Sim, hooks=None):
    """An IM 1 interrupt (or RST 38) the original takes at 0x0038: the original ROM's handler and the patched alt ROM
    image's handler run from the same state to the return. -> failures. This is the path NextZXOS's DivMMC trap hides on
    the Next; here 0x0038 really reaches the alt ROM, as on any loader or machine without that trap."""
    sp0 = R[12]
    ret = get(sp0) | get(sp0 + 1) << 8

    def stop(r):
        return r[24] == ret and r[12] == sp0 + 2
    O, P = _overlays(get, alt, {})
    o, p = O(), P()
    so = _machine(Sim, o, list(R), NextState(b''))
    sp_ = _machine(Sim, p, list(R), NextState(b''), 'p')
    if not _run(so, stop, 20000):
        return ['original handler did not return']
    f = []
    if hooks:
        h0, h1 = hooks
        Rp, ops, pm = sp_.registers, sp_.opcodes, sp_.memory
        n = ran = 0
        while not stop(Rp) and n < 20000:
            if h0 <= Rp[24] < h1:
                ran += 1
            ops[pm[Rp[24]]]()
            n += 1
        if ran:
            f.append(('hook code ran', ran))
        if not stop(Rp):
            return f + ['alt ROM handler did not return']
    elif not _run(sp_, stop, 20000):
        return ['alt ROM handler did not return']
    ro, rp = so.registers, sp_.registers
    diff = [i for i in CMP if ro[i] != rp[i]]
    if diff:
        f.append(('registers differ', diff))
    md = [a for a in set(o.ov) | set(p.ov) if o[a] != p[a]]
    if md:
        f.append(('memory differs', len(md), sorted(md)[:4]))
    if getattr(p, 'romw', 0):
        f.append(('alt ROM handler wrote ROM',))
    return f


