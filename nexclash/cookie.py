def _to_site(R, mem, gaddr, x, y, ink, ix):
    """From a captured draw-site state: re-enter the set-up with DE = graphic, object ix at (x, y) -> the state at
    the site (registers), memory updated in place."""
    Sim = _rw()
    mem[ix + 1], mem[ix + 2], mem[ix + 3] = x, y, ink
    r = list(R)
    r[24] = NW_ENTRY
    r[4], r[5] = gaddr >> 8, gaddr & 255
    r[8], r[9] = ix >> 8, ix & 255
    from .simpool import machine, copy_back
    sim = machine(Sim, mem, r, 'site', copy=True)
    done = _run(sim, lambda q: q[24] == NW, 5000)
    copy_back(sim, mem)
    if not done:
        return None
    return list(sim.registers)


def unit_tests(patch, states, neg=None, m0=None):
    c = collections.Counter()
    alt = _alt(patch)
    Sim = _rw()
    gk = sorted(k for k, v in graphics(m0).items() if v is not None and layout(v) is not None)

    def one(pt, kind, R, mem, attrs):
        ns = NextState(pt.pats)
        ns.attr = [list(a) for a in attrs]
        return event(pt, kind, mem.__getitem__, R, ns, alt, Sim) + (ns,)

    done = set()
    for pc, R, mem0 in [(s[0], s[1], s[2]) for s in states if isinstance(s[0], int)]:
        for speed in (0, 1, 2, 3):                  # the caller's speed comes back whatever it was (card patch.restore-speed)
            fl = plot_event(patch, pc, mem0.__getitem__, R, alt, Sim, speed)
            c['speed cases %s' % ('ok' if not fl else 'FAIL!')] += 1
    states = [s for s in states if not isinstance(s[0], int)]
    for kind, R, mem0, attrs in states:
        if kind in done:
            continue
        done.add(kind)
        if kind == 'nw':
            negd = []
            for key in gk:
                for x, y in POS:
                    for ink in INKS:
                        for ix in (OBJ0, OBJ0 + 8 * (NOBJ - 1)):
                            mem = bytearray(mem0)
                            r = _to_site(R, mem, key[1], x, y, ink, ix)
                            if r is None:
                                c['graphic cases: setup did not reach the site FAIL!'] += 1
                                continue
                            fl, npx, note, _ = one(patch, kind, r, mem, attrs)
                            c['graphic cases %s' % ('ok' if not fl and note in (None, 'edge') else 'FAIL!')] += 1
                            if fl and c['  fail example'] < 5:
                                c['  fail example'] += 1
                                c['  %s x %d y %d ink %d ix %d %s' % (key, x, y, ink, ix, str(fl[:2])[:150])] += 1
                            if neg is not None and npx and len(negd) < 40 and ink == 0x47 and ix == OBJ0:
                                fln = one(neg, kind, r, mem, attrs)[0]
                                negd.append(bool(fln))
            c['negative control detected'] += sum(negd)
            c['negative control NOT DETECTED!'] += len(negd) - sum(negd)
            # guard: IX not an object slot (between two slots, before the table, after it, the figures the game
            # leaves on the screen) -> no sprite changes, the figure is the game's
            for ix in (OBJ0 + 4, OBJ0 - 8, OBJ0 + 8 * NOBJ) + STATIC_IX:
                mem = bytearray(mem0)
                r = _to_site(R, mem, gk[0][1], 100, 100, 0x47, ix)
                at = [list(a) for a in attrs]
                fl, _, note, ns = one(patch, kind, r, mem, at)
                ok = not fl and note == 'left' and ns.attr == at
                c['IX outside the object table (guard: no sprite) %s' % ('ok' if ok else 'FAIL!')] += 1
            # a graphic the table does not hold: the object's sprites go off (the figure stays the game's, uncoloured)
            mem = bytearray(mem0)
            g = 0x5B10
            mem[g:g + 5] = bytes((2, 0xFF, 0xFF, 0xFF, 0xFF))
            r = _to_site(R, mem, g, 100, 100, 0x47, OBJ0)
            at = [list(a) for a in attrs]
            for i in range(SPO):
                at[i][3] |= 0x80
            ns = NextState(patch.pats)
            ns.attr = [list(a) for a in at]
            event(patch, kind, mem.__getitem__, r, ns, alt, Sim)
            c['a graphic not in the table: the object\'s sprites off %s' % ('ok' if not any(ns.attr[i][3] & 0x80 for i in range(SPO)) else 'FAIL!')] += 1
        elif kind == 'er':
            for ix in (OBJ0, OBJ0 + 8 * (NOBJ - 1)):
                r = list(R)
                r[8], r[9] = ix >> 8, ix & 255
                at = [list(a) for a in attrs]
                for i in range(128):
                    at[i][3] |= 0x80
                fl = one(patch, kind, r, bytearray(mem0), at)[0]
                c['erase cases %s' % ('ok' if not fl else 'FAIL!')] += 1
        elif kind == 'cls':
            at = [list(a) for a in attrs]
            for i in range(NSPR):
                at[i][3] |= 0x80
            fl = one(patch, kind, list(R), bytearray(mem0), at)[0]
            c['screen clear cases %s' % ('ok' if not fl else 'FAIL!')] += 1
        elif kind == 'at':
            # the paint through every changed CALL / JP, at the top and the bottom of the screen, for the first and
            # the last object: nothing painted, everything else the game's
            for site in AT_SITES:
                for ix in (OBJ0, OBJ0 + 8 * (NOBJ - 1)):
                    for y in (10, 100, 190):
                        mem = bytearray(mem0)
                        r = list(R)
                        r[24] = site
                        r[8], r[9] = ix >> 8, ix & 255
                        mem[ix + 3] = 0x46
                        mem[0x5F1F], mem[0x5F20] = 100, y
                        fl = one(patch, kind, r, mem, attrs)[0]
                        c['paint cases %s' % ('ok' if not fl else 'FAIL!')] += 1
                        if fl and c['  paint fail example'] < 3:
                            c['  paint fail example'] += 1
                            c['  site %04X ix %04X y %d %s' % (site, ix, y, str(fl[:2])[:150])] += 1
    return c


def pace_negatives(patch):
    """Broken copies of the pace hooks, each of which the replay must catch: {name: patch}. The bytes are the assembler's,
    found by the instruction: nextreg 7,3 (ED 91 07 03) in the entries, nextreg 7,a (ED 92 07) in the ends."""
    import copy
    out = {}
    syms = patch.syms

    def variant(name, fn):
        q = copy.copy(patch)
        b = bytearray(patch.ram_code)
        fn(b)
        q.sites = [(a, o, bytes(b) if a == RAM_ORG else n) for a, o, n in patch.sites]
        out[name] = q

    def nop(pat, start, count=1):
        def f(b):
            i = start - RAM_ORG
            for _ in range(count):
                i = b.index(pat, i)
                b[i:i + len(pat)] = bytes(len(pat))
        return f
    variant('window never opened', nop(bytes.fromhex('ed910703'), syms['e_p3c']))
    variant('window never closed', nop(bytes.fromhex('ed9207'), syms['e_x1']))

    def r_off(b):       # the delta in e_nw's R_SET, one off: push af / ld a,n / call hlib_r_set
        i = b.index(bytes.fromhex('f53e'), syms['e_nw'] - RAM_ORG)
        b[i + 2] = (b[i + 2] + 1) & 0x7F
    variant('R off by one after a draw', r_off)

    def r_off2(b):      # the same in an entry
        i = b.index(bytes.fromhex('f53e'), syms['e_p3c'] - RAM_ORG)
        b[i + 2] = (b[i + 2] + 1) & 0x7F
    variant('R off by one after an entry', r_off2)

    q = copy.copy(patch)    # the paint's store left as the game's
    q.sites = [(a, o, o if a == STORE else n) for a, o, n in patch.sites]
    out['the colour is painted after all'] = q
    return out


def negative_patch(patch):
    """Broken copy: every pattern shifted one pixel right (the pixel check must fail)."""
    import copy
    q = copy.copy(patch)
    p = bytearray(patch.pats)
    out = bytearray(len(p))
    for r in range(len(p) // 8):
        row = int.from_bytes(p[8 * r:8 * r + 8], 'big')
        out[8 * r:8 * r + 8] = (row >> 4).to_bytes(8, 'big')
    q.pats = bytes(out)
    return q


def rom3_left_patch(patch=None):
    """The build before 2026-11-04 (published 11fdc5ab): only the hook bytes 0x386E.. written over NextZXOS's ROM3."""
    import copy
    q = copy.copy(patch or CookiePatch())
    q.altrom = q.hook_range
    q.altrom_low = None
    return q


